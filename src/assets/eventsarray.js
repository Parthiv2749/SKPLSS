  const updateEventStatuses = (events) => {
  const today = new Date();
  today.setHours(0, 0, 0, 0); // Normalize time to compare only date

  return events.map((event) => {
    const fromDate = new Date(event.fromDate);
    const toDate = new Date(event.toDate);

    let status = "Upcoming";
    if (today > toDate) {
      status = "Past";
    } else if (today >= fromDate && today <= toDate) {
      status = "Ongoing";
    }

    return {
      ...event,
      status,
    };
  });
};

export default updateEventStatuses(events);